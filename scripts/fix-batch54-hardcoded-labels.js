const languages = ['en', 'zh', 'ja', 'ko', 'es', 'pt', 'fr', 'de', 'ru', 'ar'];

languages.forEach(lang => {
  const filePath = `src/messages/${lang}.json`;
  const data = JSON.parse(fs.readFileSync(filePath, 'utf8'));
  
  Object.keys(uiLabels).forEach(slug => {
    if (data.tools[slug] && uiLabels[slug][lang]) {
      Object.keys(uiLabels[slug][lang]).forEach(key => {
        data.tools[slug][key] = uiLabels[slug][lang][key];
      });
    }
  });
  
  fs.writeFileSync(filePath, JSON.stringify(data, null, 2) + '\n', 'utf8');
  console.log(`Updated ${lang}.json with UI labels`);
});

console.log('\nDone!');
