// Main function to add translations
locales.forEach(locale => {
  const filePath = path.join(__dirname, '..', 'src', 'messages', `${locale}.json`);
  const data = JSON.parse(fs.readFileSync(filePath, 'utf8'));
  
  Object.keys(translations).forEach(toolSlug => {
    if (data.tools && data.tools[toolSlug]) {
      const toolTrans = translations[toolSlug][locale] || translations[toolSlug]['en'];
      Object.keys(toolTrans).forEach(key => {
        if (!data.tools[toolSlug][key]) {
          data.tools[toolSlug][key] = toolTrans[key];
        }
      });
    }
  });
  
  fs.writeFileSync(filePath, JSON.stringify(data, null, 2) + '\n', 'utf8');
  console.log(`Updated ${locale}.json`);
});

console.log('Done!');
