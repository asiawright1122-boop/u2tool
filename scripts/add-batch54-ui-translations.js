const languages = ['en', 'zh', 'ja', 'ko', 'es', 'pt', 'fr', 'de', 'ru', 'ar'];

languages.forEach(lang => {
  const filePath = `src/messages/${lang}.json`;
  const data = JSON.parse(fs.readFileSync(filePath, 'utf8'));
  
  batch54Tools.forEach(slug => {
    if (data.tools[slug]) {
      // 添加通用 UI 键
      Object.keys(commonUIKeys[lang]).forEach(key => {
        if (!data.tools[slug][key]) {
          data.tools[slug][key] = commonUIKeys[lang][key];
        }
      });
    }
  });
  
  fs.writeFileSync(filePath, JSON.stringify(data, null, 2) + '\n', 'utf8');
  console.log(`Updated ${lang}.json`);
});

console.log('\nDone!');
